#!/usr/bin/env python3
"""Generate P4 constants from the canonical JSON INT wire schema.

The JSON file is the single source of truth consumed by the Python receiver
and this generator.  P4 field declarations remain explicit because p4c needs
compile-time bit widths; ``--check`` makes CI fail when they drift.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "idn-system" / "config" / "int_schema.json"
OUTPUT = ROOT / "p4" / "int_schema.p4"


def render(schema: dict) -> str:
    header_bits = sum(int(item["bit_width"]) for item in schema["header"]["fields"])
    hop_bits = sum(int(item["bit_width"]) for item in schema["hop_record"]["fields"])
    if header_bits != int(schema["header"]["length_bytes"]) * 8:
        raise ValueError("INT header field widths do not match length_bytes")
    if hop_bits != int(schema["hop_record"]["length_bytes"]) * 8:
        raise ValueError("INT hop field widths do not match length_bytes")
    return "\n".join([
        "/* Generated by p4/generate_int_schema.py; do not edit by hand. */",
        f"const bit<16> IDN_INT_MAGIC = 0x{int(schema['header']['magic']):04x};",
        f"const bit<8> IDN_INT_VERSION = {int(schema['schema_version'])};",
        f"const bit<8> INT_MAX_HOPS = {int(schema['max_hops'])};",
        f"const bit<16> ETHERTYPE_INTENT = 0x{int(schema['ether_type']):04x};",
        f"const bit<8> INT_IP_PROTOCOL = {int(schema['ip_protocol'])};",
        f"const bit<16> IDN_INT_HOP_VALID = 1;",
        "",
    ])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(json.loads(SCHEMA.read_text(encoding="utf-8")))
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if actual != expected:
            raise SystemExit("p4/int_schema.p4 is stale; run generate_int_schema.py")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
