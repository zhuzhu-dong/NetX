#!/usr/bin/env python3
"""
generate_java_constants.py — Generate P4InfoConstants.java from p4info.txt.

Parses the compiled P4Info protobuf text format and emits:
  1. A Java source file with public static final int constants for every table,
     action, meter, controller metadata, and register defined in the P4 program.
  2. Optionally, a shell-sourcable env file with the same IDs.

Usage:
  python3 generate_java_constants.py \
      --p4info p4/build/idn_basic.p4info.txt \
      --output onos-pipeconf/src/main/java/.../P4InfoConstants.java \
      --shell-output p4/build/p4info.env

The output files are deterministic (no timestamps) and should be committed to git.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path
from types import SimpleNamespace

# Workaround: the p4runtime wheel ships pre-compiled _pb2.py generated by
# older protoc (3.x).  protobuf >= 4.21 rejects those descriptors with
# "Descriptors cannot be created directly".  The pure-Python implementation
# accepts them.
os.environ.setdefault("PROTOCOL_BUFFERS_PYTHON_IMPLEMENTATION", "python")

try:
    import google.protobuf.text_format as _text_format
    from p4.config.v1 import p4info_pb2
except ModuleNotFoundError:
    _text_format = None
    p4info_pb2 = None


def _safe_java_name(name: str) -> str:
    """Convert a P4 fully-qualified name to a Java-safe identifier."""
    return name.replace(".", "_")


def _safe_shell_name(name: str) -> str:
    """Convert a P4 fully-qualified name to a shell-safe UPPER_SNAKE identifier."""
    return name.replace(".", "_").upper()


def _entity_name(entity) -> str:
    """Return the preamble name for sorting."""
    return entity.preamble.name


def _parse_entities(raw: str, plural_name: str) -> list[SimpleNamespace]:
    pattern = re.compile(
        rf"(?ms)^{re.escape(plural_name)}\s*\{{\s*preamble\s*\{{\s*"
        r"id:\s*(\d+)\s*name:\s*\"([^\"]+)\""
    )
    return [
        SimpleNamespace(preamble=SimpleNamespace(id=int(entity_id), name=name))
        for entity_id, name in pattern.findall(raw)
    ]


def parse_p4info(p4info_path: Path):
    """Parse p4info.txt and return the parsed P4Info protobuf message."""
    raw = p4info_path.read_text(encoding="utf-8")
    if p4info_pb2 is not None and _text_format is not None:
        p4info = p4info_pb2.P4Info()
        _text_format.Parse(raw, p4info)
        return p4info
    # The constant generator only needs preamble IDs and names.  Keep the P4
    # build usable in minimal WSL environments where p4c is installed through
    # Docker but the Python p4runtime/protobuf wheels are not.
    return SimpleNamespace(
        tables=_parse_entities(raw, "tables"),
        actions=_parse_entities(raw, "actions"),
        counters=_parse_entities(raw, "counters"),
        direct_counters=_parse_entities(raw, "direct_counters"),
        direct_meters=_parse_entities(raw, "direct_meters"),
        controller_packet_metadata=_parse_entities(raw, "controller_packet_metadata"),
        registers=_parse_entities(raw, "registers"),
        action_profiles=_parse_entities(raw, "action_profiles"),
    )


def generate_java(p4info: p4info_pb2.P4Info, output_path: Path) -> None:
    """Write P4InfoConstants.java from a parsed P4Info."""

    lines: list[str] = []
    w = lines.append

    # ── File header ───────────────────────────────────────────────────
    w("package org.onosproject.pipelines.idn;")
    w("")
    w("/**")
    w(" * Auto-generated from idn_basic.p4info.txt — DO NOT EDIT BY HAND.")
    w(" *")
    w(" * <p>Run {@code p4/compile.sh} after modifying {@code p4/idn_basic.p4}")
    w(" * to regenerate this file.")
    w(" *")
    w(" * <p>Generator: {@code p4/generate_java_constants.py}")
    w(" */")
    w("public final class P4InfoConstants {")
    w("")
    w("    private P4InfoConstants() {}")
    w("")

    # ── Tables ────────────────────────────────────────────────────────
    w("    // ── Tables ───────────────────────────────────────────────")
    for t in sorted(p4info.tables, key=_entity_name):
        java_name = _safe_java_name(t.preamble.name)
        w(f"    public static final int TABLE_ID_{java_name} = {t.preamble.id};")
    w("")

    # ── Actions ───────────────────────────────────────────────────────
    w("    // ── Actions ──────────────────────────────────────────────")
    for a in sorted(p4info.actions, key=_entity_name):
        java_name = _safe_java_name(a.preamble.name)
        w(f"    public static final int ACTION_ID_{java_name} = {a.preamble.id};")
    w("")

    # ── Direct Meters ─────────────────────────────────────────────────
    if p4info.counters:
        w("    // ── Counters ─────────────────────────────────────────────")
        for c in sorted(p4info.counters, key=_entity_name):
            java_name = _safe_java_name(c.preamble.name)
            w(f"    public static final int COUNTER_ID_{java_name} = {c.preamble.id};")
        w("")

    # ── Direct Counters ────────────────────────────────────────────────
    if p4info.direct_counters:
        w("    // ── Direct Counters ──────────────────────────────────────")
        for c in sorted(p4info.direct_counters, key=_entity_name):
            java_name = _safe_java_name(c.preamble.name)
            w(f"    public static final int COUNTER_ID_{java_name} = {c.preamble.id};")
        w("")

    # ── Direct Meters ─────────────────────────────────────────────────
    if p4info.direct_meters:
        w("    // ── Direct Meters ────────────────────────────────────────")
        for m in sorted(p4info.direct_meters, key=_entity_name):
            java_name = _safe_java_name(m.preamble.name)
            w(f"    public static final int METER_ID_{java_name} = {m.preamble.id};")
        w("")

    # ── Controller Packet Metadata ────────────────────────────────────
    if p4info.controller_packet_metadata:
        w("    // ── Controller Packet Metadata ───────────────────────────")
        for cm in sorted(p4info.controller_packet_metadata, key=_entity_name):
            java_name = _safe_java_name(cm.preamble.name)
            w(f"    public static final int CTRL_META_ID_{java_name} = {cm.preamble.id};")
        w("")

    # ── Registers ─────────────────────────────────────────────────────
    if p4info.registers:
        w("    // ── Registers ────────────────────────────────────────────")
        for r in sorted(p4info.registers, key=_entity_name):
            java_name = _safe_java_name(r.preamble.name)
            w(f"    public static final int REGISTER_ID_{java_name} = {r.preamble.id};")
        w("")

    # ── Action Profiles (if any) ──────────────────────────────────────
    if p4info.action_profiles:
        w("    // ── Action Profiles ──────────────────────────────────────")
        for ap in sorted(p4info.action_profiles, key=_entity_name):
            java_name = _safe_java_name(ap.preamble.name)
            w(f"    public static final int ACTION_PROFILE_ID_{java_name} = {ap.preamble.id};")
        w("")

    w("}")

    # ── Write output ──────────────────────────────────────────────────
    content = "\n".join(lines) + "\n"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")
    print(f"Generated {output_path}")


def generate_shell(p4info: p4info_pb2.P4Info, output_path: Path) -> None:
    """Generate a shell-sourcable file with P4 table/action IDs as variables."""
    lines: list[str] = []
    w = lines.append
    w("# Auto-generated from idn_basic.p4info.txt — DO NOT EDIT BY HAND.")
    w("# Source this file in shell scripts to get P4 entity IDs, e.g.:")
    w("#   source p4/build/p4info.env")
    w("#   echo $P4_TABLE_MYINGRESS_IPV4_ROUTING")
    w("")

    for t in p4info.tables:
        name = _safe_shell_name(t.preamble.name)
        w(f"P4_TABLE_{name}={t.preamble.id}")

    for a in p4info.actions:
        name = _safe_shell_name(a.preamble.name)
        w(f"P4_ACTION_{name}={a.preamble.id}")

    for c in p4info.direct_counters:
        name = _safe_shell_name(c.preamble.name)
        w(f"P4_COUNTER_{name}={c.preamble.id}")

    for c in p4info.counters:
        name = _safe_shell_name(c.preamble.name)
        w(f"P4_COUNTER_{name}={c.preamble.id}")

    for m in p4info.direct_meters:
        name = _safe_shell_name(m.preamble.name)
        w(f"P4_METER_{name}={m.preamble.id}")

    content = "\n".join(lines) + "\n"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")
    print(f"Generated {output_path}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate P4InfoConstants.java (and optionally p4info.env) from p4info.txt"
    )
    parser.add_argument(
        "--p4info",
        required=True,
        type=Path,
        help="Path to idn_basic.p4info.txt",
    )
    parser.add_argument(
        "--output",
        required=True,
        type=Path,
        help="Path for output P4InfoConstants.java",
    )
    parser.add_argument(
        "--shell-output",
        type=Path,
        default=None,
        help="Optional: also generate a shell-sourcable env file with P4 IDs",
    )
    args = parser.parse_args()

    if not args.p4info.exists():
        print(f"ERROR: p4info file not found: {args.p4info}", file=sys.stderr)
        print("  Run 'p4/compile.sh' first.", file=sys.stderr)
        sys.exit(1)

    p4info = parse_p4info(args.p4info.resolve())
    generate_java(p4info, args.output.resolve())

    if args.shell_output:
        generate_shell(p4info, args.shell_output.resolve())


if __name__ == "__main__":
    main()
