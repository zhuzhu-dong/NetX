class TestActionParams:
    """Action parameter IDs and bitwidths must match."""

    def test_param_ids_and_bitwidths_match(self, compiled_p4info, registry):
        p4_actions = extract_actions(compiled_p4info)
        for aname, adata in p4_actions.items():
            p4_params = adata["params"]
            reg_params_list = registry["_ACTIONS"][aname]["params"]
            reg_params = {p["name"]: {"id": p["id"], "bitwidth": p["bitwidth"]} for p in reg_params_list}

            assert set(p4_params) == set(reg_params), \
                f"Action '{aname}' param name mismatch:\n  p4info: {sorted(p4_params)}\n  registry: {sorted(reg_params)}"

            for pname, pdata in p4_params.items():
                assert pdata["id"] == reg_params[pname]["id"], \
                    f"Action '{aname}' param '{pname}' id mismatch: p4info={pdata['id']}, registry={reg_params[pname]['id']}"
                assert pdata["bitwidth"] == reg_params[pname]["bitwidth"], \
                    f"Action '{aname}' param '{pname}' bitwidth mismatch: p4info={pdata['bitwidth']}, registry={reg_params[pname]['bitwidth']}"


class TestMatchFields:
    """Table match field IDs, types, and bitwidths must match."""

    def test_match_fields_match(self, compiled_p4info, registry):
        p4_tables = extract_tables(compiled_p4info)
        for tname, tdata in p4_tables.items():
            p4_fields = tdata["match_fields"]
            reg_fields = registry["_TABLES"][tname]["match_fields"]

            p4_names = set(p4_fields)
            reg_names = set(reg_fields)
            assert p4_names == reg_names, \
                f"Table '{tname}' match field mismatch:\n  p4info: {sorted(p4_names)}\n  registry: {sorted(reg_names)}"

            for fname, fdata in p4_fields.items():
                reg_fdata = reg_fields[fname]
                assert fdata["field_id"] == reg_fdata["field_id"], \
                    f"Table '{tname}' field '{fname}' field_id mismatch: p4info={fdata['field_id']}, registry={reg_fdata['field_id']}"
                assert fdata["match_type"] == reg_fdata["match_type"], \
                    f"Table '{tname}' field '{fname}' match_type mismatch: p4info={fdata['match_type']}, registry={reg_fdata['match_type']}"
                assert fdata["bitwidth"] == reg_fdata["bitwidth"], \
                    f"Table '{tname}' field '{fname}' bitwidth mismatch: p4info={fdata['bitwidth']}, registry={reg_fdata['bitwidth']}"


class TestTableActions:
    """Table action_refs must match the action IDs declared in p4info."""

    def test_table_action_refs_match(self, compiled_p4info, registry):
        p4_tables = extract_tables(compiled_p4info)
        p4_actions = extract_actions(compiled_p4info)
        # Build action_id → name map
        id_to_name = {adata["id"]: aname for aname, adata in p4_actions.items()}

        for tname, tdata in p4_tables.items():
            reg_actions = registry["_TABLES"][tname]["actions"]
            reg_ids = {a["id"] for a in reg_actions}
            reg_names = {a["name"] for a in reg_actions}
            p4_ids = tdata["action_ids"]

            assert p4_ids == reg_ids, \
                f"Table '{tname}' action_refs mismatch:\n  p4info ids: {p4_ids}\n  registry ids: {reg_ids}"

            # Also verify names are consistent with global action registry
            for aid in p4_ids:
                expected_name = id_to_name.get(aid, "?")
                assert expected_name in reg_names, \
                    f"Table '{tname}' action id={aid} should be '{expected_name}', not found in registry names"


class TestControllerMetadata:
    """Controller packet metadata must match (critical for packet-in/out)."""

    def test_controller_metadata_32bit(self, compiled_p4info, registry):
        """ADR-0001: controller metadata must be 32-bit."""
        p4_meta = _to_list(compiled_p4info.get("controller_packet_metadata"))
        for cm in p4_meta:
            name = cm.get("name", "")
            meta_fields = _to_list(cm.get("metadata"))
            for mf in meta_fields:
                bw = int(mf.get("bitwidth", 0))
                assert bw == 32, \
                    f"Controller metadata '{name}.{mf.get('name', '?')}' is {bw}-bit, must be 32-bit (ADR-0001)"

    def test_controller_metadata_ids_match(self, compiled_p4info, registry):
        p4_meta = _to_list(compiled_p4info.get("controller_packet_metadata"))
        reg_meta = registry["_CONTROLLER_METADATA"]
        for cm in p4_meta:
            name = cm.get("name", "")
            assert name in reg_meta, \
                f"Controller metadata '{name}' missing from _CONTROLLER_METADATA"
            assert int(cm.get("id", 0)) == reg_meta[name]["id"], \
                f"Controller metadata '{name}' id mismatch"


class TestToDict:
    """Verify to_dict() output can be consumed by P4RuleVerifierAgent."""

    def test_to_dict_has_required_keys(self, registry):
        from mcp_servers.p4info_registry import p4info_registry
        d = p4info_registry.to_dict()
        for key in ("tables", "actions"):
            assert key in d, f"to_dict() missing key: {key}"
        assert isinstance(d["tables"], list)
        assert len(d["tables"]) > 0
        assert isinstance(d["actions"], list)
        assert len(d["actions"]) > 0

    def test_to_dict_tables_consumable_by_rule_verifier(self, registry):
        """P4RuleVerifierAgent expects: name, match_fields[{name,match_type,bitwidth}], action_refs, size."""
        from mcp_servers.p4info_registry import p4info_registry
        d = p4info_registry.to_dict()
        for t in d["tables"]:
            assert "name" in t
            assert "match_fields" in t
            assert "action_refs" in t
            assert "size" in t
            for mf in t["match_fields"]:
                assert "name" in mf, f"match_field missing name in table {t['name']}"
                assert "match_type" in mf, f"match_field missing match_type in table {t['name']}"
                assert "bitwidth" in mf, f"match_field missing bitwidth in table {t['name']}"

    def test_to_dict_actions_consumable_by_rule_verifier(self, registry):
        """P4RuleVerifierAgent expects: name, params[{name, bitwidth}]."""
        from mcp_servers.p4info_registry import p4info_registry
        d = p4info_registry.to_dict()
        for a in d["actions"]:
            assert "name" in a
            assert "params" in a
            for p in a["params"]:
                assert "name" in p, f"param missing name in action {a['name']}"
                assert "bitwidth" in p, f"param missing bitwidth in action {a['name']}"
