# ── lightweight p4info.txt parser (independent cross-check for protobuf parse) ─

def _tokenize(text: str) -> list[tuple[str, str | None, str | None]]:
    import re
    kv_re = re.compile(r'^\s*(\w+):\s*(.+)$')
    str_re = re.compile(r'^"([^"]*)"$')

    tokens: list[tuple[str, str | None, str | None]] = []
    for raw in text.splitlines():
        line = raw
        open_count = 0
        while line.endswith("{"):
            line = line[:-1].rstrip()
            open_count += 1
        close_count = 0
        while line.endswith("}"):
            line = line[:-1].rstrip()
            close_count += 1
        line = line.strip()
        if not line:
            for _ in range(open_count):
                tokens.append(("open", None, None))
            for _ in range(close_count):
                tokens.append(("close", None, None))
            continue
        m = kv_re.match(line)
        if m:
            val = m.group(2).strip()
            sm = str_re.match(val)
            tokens.append(("kv", m.group(1), sm.group(1) if sm else val))
        elif open_count > 0:
            tokens.append(("block_name", line, None))
        for _ in range(open_count):
            tokens.append(("open", None, None))
        for _ in range(close_count):
            tokens.append(("close", None, None))
    return tokens


def _parse_tokens(tokens: list) -> dict:
    i = 0
    result: dict[str, Any] = {}
    while i < len(tokens):
        tt, key, val = tokens[i]
        if tt in ("kv", "block_name") and i + 1 < len(tokens) and tokens[i + 1][0] == "open":
            assert key is not None
            depth = 1
            j = i + 2
            while j < len(tokens) and depth > 0:
                nt = tokens[j][0]
                if nt == "open":
                    depth += 1
                elif nt == "close":
                    depth -= 1
                j += 1
            inner = _parse_tokens(tokens[i + 2 : j - 1])
            existing = result.get(key)
            if existing is None:
                result[key] = inner
            elif isinstance(existing, list):
                existing.append(inner)
            else:
                result[key] = [existing, inner]
            i = j
        elif tt == "kv":
            assert key is not None
            result[key] = val
            i += 1
        elif tt == "open":
            depth = 1
            j = i + 1
            while j < len(tokens) and depth > 0:
                nt = tokens[j][0]
                if nt == "open":
                    depth += 1
                elif nt == "close":
                    depth -= 1
                j += 1
            inner = _parse_tokens(tokens[i + 1 : j - 1])
            for ik, iv in inner.items():
                existing = result.get(ik)
                if existing is None:
                    result[ik] = iv
                elif isinstance(existing, list):
                    existing.append(iv)
                else:
                    result[ik] = [existing, iv]
            i = j
        else:
            i += 1
    return result


def _flatten_preamble(tree: Any) -> Any:
    if isinstance(tree, dict):
        if "preamble" in tree and isinstance(tree["preamble"], dict):
            for k, v in tree["preamble"].items():
                tree.setdefault(k, v)
            del tree["preamble"]
        if "spec" in tree and isinstance(tree["spec"], dict):
            for k, v in tree["spec"].items():
                tree.setdefault(k, v)
            del tree["spec"]
        for k, v in tree.items():
            if isinstance(v, (dict, list)):
                tree[k] = _flatten_preamble(v)
    elif isinstance(tree, list):
        return [_flatten_preamble(item) for item in tree]
    return tree


def _to_list(v: Any) -> list:
    if v is None:
        return []
    if isinstance(v, list):
        return v
    return [v]


def parse_p4info(path: Path) -> dict:
    """Parse compiled p4info.txt into a nested dict with preambles flattened."""
    text = path.read_text(encoding="utf-8")
    tokens = _tokenize(text)
    tree = _parse_tokens(tokens)
    return _flatten_preamble(tree)


# ── extractors ──────────────────────────────────────────────────────────────

def extract_tables(tree: dict) -> dict[str, dict]:
    """Return {table_name: {id, match_fields: {name: {field_id, match_type, bitwidth}},
                             action_ids: set, size, action_profile_id?}}"""
    tables: dict[str, dict] = {}
    for t in _to_list(tree.get("tables")):
        name = t.get("name", "")
        if not name:
            continue
        mf_list = _to_list(t.get("match_fields"))
        match_fields: dict[str, dict] = {}
        for mf in mf_list:
            fn = mf.get("name", "")
            if fn:
                match_fields[fn] = {
                    "field_id": int(mf.get("id", 0)),
                    "match_type": str(mf.get("match_type", "EXACT")).upper(),
                    "bitwidth": int(mf.get("bitwidth", 0)),
                }
        refs = _to_list(t.get("action_refs"))
        action_ids: set[int] = {int(ref.get("id", 0)) for ref in refs if ref.get("id")}

        entry: dict[str, Any] = {
            "id": int(t.get("id", 0)),
            "match_fields": match_fields,
            "action_ids": action_ids,
            "size": int(t.get("size", 0)),
        }
        if t.get("implementation_id"):
            entry["action_profile_id"] = int(t["implementation_id"])
        tables[name] = entry
    return tables


def extract_actions(tree: dict) -> dict[str, dict]:
    """Return {action_name: {id, params: {name: {id, bitwidth}}}}"""
    actions: dict[str, dict] = {}
    for a in _to_list(tree.get("actions")):
        name = a.get("name", "")
        if not name:
            continue
        params: dict[str, dict] = {}
        for p in _to_list(a.get("params")):
            pname = p.get("name", "")
            if pname:
                params[pname] = {
                    "id": int(p.get("id", 0)),
                    "bitwidth": int(p.get("bitwidth", 0)),
                }
        actions[name] = {"id": int(a.get("id", 0)), "params": params}
    return actions


