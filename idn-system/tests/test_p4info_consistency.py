"""Verify p4info_registry.py matches the compiled P4Info.

The registry now loads p4info.txt at import time via protobuf.  This test
uses an independent lightweight parser to cross-validate the protobuf
parse result — two completely different parsers should agree on the same
file.

When p4info.txt is not found the test is skipped (useful in CI environments
without the P4 toolchain).

Usage:
    pytest tests/test_p4info_consistency.py -v
    pytest -m p4consistency            # only this test
    pytest -m "not p4consistency"      # skip this test
"""
