class TestTableIds:
    """Every table in p4info.txt must match the registry."""

    def test_table_count_matches(self, compiled_p4info, registry):
        p4_tables = extract_tables(compiled_p4info)
        reg_tables = registry["_TABLES"]
        assert set(p4_tables) == set(reg_tables), \
            f"Table name mismatch:\n  p4info: {sorted(p4_tables)}\n  registry: {sorted(reg_tables)}"

    def test_table_ids_match(self, compiled_p4info, registry):
        p4_tables = extract_tables(compiled_p4info)
        for tname, tdata in p4_tables.items():
            reg_id = registry["_TABLES"][tname]["id"]
            assert tdata["id"] == reg_id, \
                f"Table '{tname}' id mismatch: p4info={tdata['id']}, registry={reg_id}"

    def test_table_sizes_match(self, compiled_p4info, registry):
        p4_tables = extract_tables(compiled_p4info)
        for tname, tdata in p4_tables.items():
            reg_size = registry["_TABLES"][tname]["size"]
            assert tdata["size"] == reg_size, \
                f"Table '{tname}' size mismatch: p4info={tdata['size']}, registry={reg_size}"

    def test_flow_type_matches_p4info(self, compiled_p4info, registry):
        p4_tables = extract_tables(compiled_p4info)
        for tname, tdata in p4_tables.items():
            reg_ft = registry["_FLOW_TYPE"].get(tname)
            assert reg_ft is not None, \
                f"Table '{tname}' missing from _FLOW_TYPE"
            assert tdata["id"] == reg_ft, \
                f"Table '{tname}' _FLOW_TYPE mismatch: p4info={tdata['id']}, registry={reg_ft}"


