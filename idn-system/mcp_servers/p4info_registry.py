"""
mcp_servers/p4info_registry.py
===============================

P4Info 注册表 —— 运行时加载编译好的 P4Info 定义。

# 系统角色
在导入时从 p4/build/idn_basic.p4info.txt 解析 P4Info protobuf 文本格式，
提供 P4 程序的结构化元数据查询（表名、字段名、动作名、参数等）。
所有 P4 相关的 Agent（PolicyCompiler、P4RuleVerifier）依赖此模块
来校验流表项的正确性。

# 技术要点
- 使用 p4runtime 的 p4info_pb2 解析 protobuf text format
- 设置 PROTOCOL_BUFFERS_PYTHON_IMPLEMENTATION=python 解决
  protobuf >= 4.21 的 descriptor 兼容性问题
- P4Info 在导入时一次性加载，运行时只读查询
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Dict, List, Optional

# Workaround: the p4runtime wheel ships pre-compiled _pb2.py generated by
# older protoc (3.x).  protobuf >= 4.21 rejects those descriptors with
# "Descriptors cannot be created directly".  The pure-Python C++-extension-
# free implementation accepts them.
os.environ.setdefault("PROTOCOL_BUFFERS_PYTHON_IMPLEMENTATION", "python")

import google.protobuf.text_format as _text_format  # noqa: E402
from p4.config.v1 import p4info_pb2  # noqa: E402


# ── Resolve path to compiled p4info.txt ────────────────────────────────

def _resolve_p4info_path() -> Path:
    """Locate p4/build/idn_basic.p4info.txt relative to the project root.

    Supports two layouts:
      Host:  <repo>/p4/build/idn_basic.p4info.txt  (parents[2] from idn-system/mcp_servers/)
      Docker: /app/p4/build/idn_basic.p4info.txt   (parents[1] — COPY idn-system/ → /app/)
    """
    this_file = Path(__file__).resolve()
    candidates = [
        this_file.parents[2] / "p4" / "build" / "idn_basic.p4info.txt",  # host layout
        this_file.parents[1] / "p4" / "build" / "idn_basic.p4info.txt",  # Docker layout
    ]
    for p4info_path in candidates:
        if p4info_path.exists():
            return p4info_path
    raise FileNotFoundError(
        f"P4Info file not found. Tried:\n"
        + "\n".join(f"  - {p}" for p in candidates)
        + "\n  Run 'p4/compile.sh' to compile the P4 program first."
    )


# ── Load & parse ───────────────────────────────────────────────────────

_p4info = p4info_pb2.P4Info()
_text_format.Parse(_resolve_p4info_path().read_text(encoding="utf-8"), _p4info)

# ── Match-type enum → string ───────────────────────────────────────────

_MATCH_TYPE = {
    p4info_pb2.MatchField.MatchType.UNSPECIFIED: "UNSPECIFIED",
    p4info_pb2.MatchField.MatchType.EXACT: "EXACT",
    p4info_pb2.MatchField.MatchType.LPM: "LPM",
    p4info_pb2.MatchField.MatchType.TERNARY: "TERNARY",
    p4info_pb2.MatchField.MatchType.RANGE: "RANGE",
    p4info_pb2.MatchField.MatchType.OPTIONAL: "OPTIONAL",
}

# ── Meter-spec unit enum → string ──────────────────────────────────────

_METER_UNIT = {
    p4info_pb2.MeterSpec.Unit.BYTES: "BYTES",
    p4info_pb2.MeterSpec.Unit.PACKETS: "PACKETS",
}

# ── Build lookup caches ────────────────────────────────────────────────

# action ID → name  (needed to resolve table.action_refs)
_action_id_to_name: Dict[int, str] = {
    a.preamble.id: a.preamble.name for a in _p4info.actions
}

# table ID → name  (needed to resolve cross-references)
_table_id_to_name: Dict[int, str] = {
    t.preamble.id: t.preamble.name for t in _p4info.tables
}

# ── Flow type → ONOS FlowRule JSON "tableId" mapping ───────────────────

_FLOW_TYPE: Dict[str, int] = {
    t.preamble.name: t.preamble.id for t in _p4info.tables
}

# ── Tables ─────────────────────────────────────────────────────────────

_TABLES: Dict[str, dict] = {}
for _t in _p4info.tables:
    _mf: Dict[str, dict] = {}
    for _f in _t.match_fields:
        _mf[_f.name] = {
            "field_id": _f.id,
            "match_type": _MATCH_TYPE.get(_f.match_type, "EXACT"),
            "bitwidth": _f.bitwidth,
        }

    _actions: List[dict] = []
    for _ar in _t.action_refs:
        _aname = _action_id_to_name.get(_ar.id, "")
        _actions.append({"name": _aname, "id": _ar.id})

    _entry: Dict[str, Any] = {
        "id": _t.preamble.id,
        "match_fields": _mf,
        "actions": _actions,
        "size": _t.size,
    }
    if _t.implementation_id:
        _entry["action_profile_id"] = _t.implementation_id

    _TABLES[_t.preamble.name] = _entry

# ── Actions ────────────────────────────────────────────────────────────

_ACTIONS: Dict[str, dict] = {}
for _a in _p4info.actions:
    _ACTIONS[_a.preamble.name] = {
        "id": _a.preamble.id,
        "params": [
            {"id": _p.id, "name": _p.name, "bitwidth": _p.bitwidth}
            for _p in _a.params
        ],
    }

# ── Action Profiles ────────────────────────────────────────────────────

_ACTION_PROFILES: Dict[str, dict] = {}
for _ap in _p4info.action_profiles:
    _table_ids = list(_ap.table_ids)
    _tname = _table_id_to_name.get(_table_ids[0], "") if _table_ids else ""
    _ACTION_PROFILES[_ap.preamble.name] = {
        "id": _ap.preamble.id,
        "table_name": _tname,
        "table_id": _table_ids[0] if _table_ids else 0,
        "with_selector": bool(_ap.with_selector),
        "size": _ap.size,
        "max_group_size": 16,
    }

# ── Direct Meters ──────────────────────────────────────────────────────

_DIRECT_METERS: Dict[str, dict] = {}
for _m in _p4info.direct_meters:
    _DIRECT_METERS[_m.preamble.name] = {
        "id": _m.preamble.id,
        "unit": _METER_UNIT.get(_m.spec.unit, "PACKETS"),
        "parent_table": _table_id_to_name.get(_m.direct_table_id, ""),
    }

# Direct counters are table-bound P4Runtime entities.  Keep their IDs and
# parent table relationship in the same runtime registry as tables/actions so
# evidence readers never depend on stale generated constants.
_DIRECT_COUNTERS: Dict[str, dict] = {}
for _c in _p4info.direct_counters:
    _DIRECT_COUNTERS[_c.preamble.name] = {
        "id": _c.preamble.id,
        "parent_table": _table_id_to_name.get(_c.direct_table_id, ""),
        "parent_table_id": _c.direct_table_id,
    }

_COUNTERS: Dict[str, dict] = {}
for _c in _p4info.counters:
    _COUNTERS[_c.preamble.name] = {
        "id": _c.preamble.id,
        "size": _c.size,
    }

# ── Registers ──────────────────────────────────────────────────────────

_REGISTERS: Dict[str, dict] = {}
for _r in _p4info.registers:
    _REGISTERS[_r.preamble.name] = {
        "id": _r.preamble.id,
        "bitwidth": _r.type_spec.bitstring.bit.bitwidth,
        "size": _r.size,
    }

# ── Controller packet metadata ─────────────────────────────────────────

_CONTROLLER_METADATA: Dict[str, dict] = {}
for _cm in _p4info.controller_packet_metadata:
    _CONTROLLER_METADATA[_cm.preamble.name] = {
        "id": _cm.preamble.id,
        "fields": [
            {"id": _m.id, "name": _m.name, "bitwidth": _m.bitwidth}
            for _m in _cm.metadata
        ],
    }


# ── Public API ─────────────────────────────────────────────────────────
#  Identical to the previous auto-generated class — consumers are
#  unaffected.

class P4InfoRegistry:
    """Centralized registry of P4 program IDs for the idn-basic pipeconf."""

    pipeconf_name = "org.onosproject.pipelines.idn-basic"

    @staticmethod
    def table_id(name: str) -> int:
        return _TABLES[name]["id"]

    @staticmethod
    def table_size(name: str) -> int:
        return _TABLES[name]["size"]

    @staticmethod
    def table_names() -> List[str]:
        return list(_TABLES.keys())

    @staticmethod
    def table_flow_type(name: str) -> int:
        """ONOS FlowRule JSON 'tableId' field."""
        return _FLOW_TYPE.get(name, 0)

    @staticmethod
    def table_name_for_id(table_id: int) -> str:
        """Return the fully-qualified P4 table name for an ONOS table ID."""
        return _table_id_to_name.get(int(table_id), "")

    @staticmethod
    def table_actions(name: str) -> List[dict]:
        return _TABLES[name]["actions"]

    @staticmethod
    def table_action_profile_id(name: str) -> Optional[int]:
        return _TABLES[name].get("action_profile_id")

    @staticmethod
    def action_id(name: str) -> int:
        return _ACTIONS[name]["id"]

    @staticmethod
    def action_params(name: str) -> List[dict]:
        return _ACTIONS[name]["params"]

    @staticmethod
    def param_id(action_name: str, param_name: str) -> Optional[int]:
        for p in _ACTIONS.get(action_name, {}).get("params", []):
            if p["name"] == param_name:
                return p["id"]
        return None

    @staticmethod
    def param_bitwidth(action_name: str, param_name: str) -> int:
        for p in _ACTIONS.get(action_name, {}).get("params", []):
            if p["name"] == param_name:
                return p.get("bitwidth", 32)
        return 32

    @staticmethod
    def action_names() -> List[str]:
        return list(_ACTIONS.keys())

    @staticmethod
    def field_id(table_name: str, field_name: str) -> Optional[int]:
        mf = _TABLES.get(table_name, {}).get("match_fields", {}).get(field_name)
        return mf["field_id"] if mf else None

    @staticmethod
    def match_type(table_name: str, field_name: str) -> Optional[str]:
        mf = _TABLES.get(table_name, {}).get("match_fields", {}).get(field_name)
        return mf["match_type"] if mf else None

    @staticmethod
    def table_match_fields(table_name: str) -> Dict[str, dict]:
        return _TABLES.get(table_name, {}).get("match_fields", {})

    @staticmethod
    def action_profile_id(name: str) -> int:
        return _ACTION_PROFILES[name]["id"]

    @staticmethod
    def action_profile_table(name: str) -> str:
        return _ACTION_PROFILES[name]["table_name"]

    @staticmethod
    def action_profile_max_group_size(name: str) -> int:
        return _ACTION_PROFILES[name]["max_group_size"]

    @staticmethod
    def action_profile_names() -> List[str]:
        return list(_ACTION_PROFILES.keys())

    @staticmethod
    def table_has_action_profile(table_name: str) -> bool:
        return bool(_TABLES.get(table_name, {}).get("action_profile_id"))

    @staticmethod
    def table_action_profile_name(table_name: str) -> str:
        """Return the action profile name for a table, e.g. 'ipv4_routing_ecmp'."""
        tdata = _TABLES.get(table_name, {})
        profile_id = tdata.get("action_profile_id")
        if profile_id is None:
            return ""
        tid = tdata["id"]
        for pname, pdata in _ACTION_PROFILES.items():
            if pdata["table_id"] == tid:
                return pname
        return ""

    @staticmethod
    def direct_meter_id(name: str) -> Optional[int]:
        m = _DIRECT_METERS.get(name)
        return m["id"] if m else None

    @staticmethod
    def direct_counter_id(name: str) -> Optional[int]:
        counter = _DIRECT_COUNTERS.get(name)
        return counter["id"] if counter else None

    @staticmethod
    def direct_counter_table(name: str) -> str:
        counter = _DIRECT_COUNTERS.get(name)
        return counter["parent_table"] if counter else ""

    @staticmethod
    def direct_counter_names() -> List[str]:
        return list(_DIRECT_COUNTERS.keys())

    @staticmethod
    def counter_id(name: str) -> Optional[int]:
        counter = _COUNTERS.get(name)
        return counter["id"] if counter else None

    @staticmethod
    def counter_names() -> List[str]:
        return list(_COUNTERS.keys())

    @staticmethod
    def counter_size(name: str) -> int:
        counter = _COUNTERS.get(name)
        return int(counter["size"]) if counter else 0

    @staticmethod
    def register_id(name: str) -> Optional[int]:
        r = _REGISTERS.get(name)
        return r["id"] if r else None

    @staticmethod
    def controller_metadata_id(name: str) -> Optional[int]:
        cm = _CONTROLLER_METADATA.get(name)
        return cm["id"] if cm else None

    @staticmethod
    def to_dict() -> Dict[str, Any]:
        tables = []
        for tname, tdata in _TABLES.items():
            t = {
                "name": tname,
                "match_fields": [
                    {"name": fname, "match_type": fdata["match_type"], "bitwidth": fdata["bitwidth"]}
                    for fname, fdata in tdata["match_fields"].items()
                ],
                "action_refs": [a["name"] for a in tdata["actions"]],
                "size": tdata["size"],
            }
            if tdata.get("action_profile_id"):
                t["action_selector"] = True
            tables.append(t)

        actions = []
        for aname, adata in _ACTIONS.items():
            actions.append({
                "name": aname,
                "params": [
                    {"name": p["name"], "bitwidth": p["bitwidth"]}
                    for p in adata["params"]
                ],
            })

        profiles = [
            {"name": pname, "table": pdata["table_name"], "with_selector": pdata["with_selector"]}
            for pname, pdata in _ACTION_PROFILES.items()
        ]

        meters = [
            {
                "name": mname,
                "id": mdata["id"],
                "unit": mdata["unit"],
                "parent_table": mdata["parent_table"],
                "size": (_TABLES.get(mdata["parent_table"]) or {}).get("size", 0),
            }
            for mname, mdata in _DIRECT_METERS.items()
        ]
        counters = [
            {
                "name": name,
                "id": data["id"],
                "parent_table": data["parent_table"],
                "parent_table_id": data["parent_table_id"],
            }
            for name, data in _DIRECT_COUNTERS.items()
        ]
        indexed_counters = [
            {"name": name, "id": data["id"], "size": data["size"]}
            for name, data in _COUNTERS.items()
        ]
        return {
            "tables": tables,
            "actions": actions,
            "action_profiles": profiles,
            "meters": meters,
            "direct_counters": counters,
            "counters": indexed_counters,
        }


    @staticmethod
    def suggested_tables_for_action(action_type: str) -> list[str]:
        """Return candidate fully-qualified P4 table names for an action type.

        The mapping is semantically derived from the P4 pipeline structure.
        Only tables that actually exist in the compiled P4Info are returned.

        Used by PolicyCompiler to select the correct target table without
        hardcoding table names.
        """
        mapping: dict[str, list[str]] = {
            "FORWARD":      ["MyIngress.ipv4_routing"],
            "DROP":         ["MyIngress.ipv4_routing", "MyIngress.acl"],
            "SET_PRIORITY": ["MyIngress.sla_enforcement"],
            "RATE_LIMIT":   ["MyIngress.sla_enforcement"],
            "MIRROR":       ["MyIngress.ipv4_routing"],
            "ACL_BLOCK":    ["MyIngress.acl"],
        }
        candidates = mapping.get(action_type.upper(), ["MyIngress.ipv4_routing"])
        all_tables = set(_TABLES.keys())
        result = [t for t in candidates if t in all_tables]
        return result or [t for t in all_tables if "ipv4_routing" in t.lower()][:1]

    @staticmethod
    def table_exists(name: str) -> bool:
        """Check whether a table (with MyIngress. prefix) exists in P4Info."""
        return name in _TABLES

    @staticmethod
    def action_exists(name: str) -> bool:
        """Check whether an action (with MyIngress. prefix) exists in P4Info."""
        return name in _ACTIONS


p4info_registry = P4InfoRegistry()
