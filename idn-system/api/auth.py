"""Minimal server-authoritative operator session authentication.

Credentials are never stored in the repository.  Production enables this
router with IDN_OPERATOR_USERNAME, IDN_OPERATOR_PASSWORD_HASH and
IDN_SESSION_SECRET supplied through the container environment.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import secrets
import time
from typing import Any

from fastapi import APIRouter, HTTPException, Request, Response
from pydantic import BaseModel, Field

router = APIRouter(prefix="/api/v1/auth", tags=["operator-auth"])

COOKIE_NAME = "idn_operator_session"
DEFAULT_TTL_SECONDS = 8 * 60 * 60

# Logout invalidates a signed session even if a previously copied browser
# cookie is replayed.  Entries contain only the opaque random nonce and are
# discarded as soon as the matching session would expire.
_revoked_session_nonces: dict[str, int] = {}


class LoginRequest(BaseModel):
    username: str = Field(min_length=1, max_length=128)
    password: str = Field(min_length=1, max_length=1024)


def auth_enabled() -> bool:
    return os.getenv("IDN_OPERATOR_AUTH_ENABLED", "false").lower() == "true"


def _config() -> tuple[str, str, bytes, int]:
    username = os.getenv("IDN_OPERATOR_USERNAME", "")
    password_hash = os.getenv("IDN_OPERATOR_PASSWORD_HASH", "")
    secret = os.getenv("IDN_SESSION_SECRET", "")
    ttl = int(os.getenv("IDN_SESSION_TTL_SECONDS", str(DEFAULT_TTL_SECONDS)))
    if not username or not password_hash or not secret:
        raise HTTPException(status_code=503, detail={"message": "Operator authentication is not configured", "reason_code": "AUTH_NOT_CONFIGURED"})
    if ttl <= 0:
        raise HTTPException(status_code=503, detail={"message": "Operator session TTL is invalid", "reason_code": "AUTH_CONFIGURATION_INVALID"})
    return username, password_hash, secret.encode("utf-8"), ttl


def _b64encode(value: bytes) -> str:
    return base64.urlsafe_b64encode(value).rstrip(b"=").decode("ascii")


def _b64decode(value: str) -> bytes:
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))


def verify_password(password: str, encoded: str) -> bool:
    """Verify PBKDF2-SHA256 hashes generated by tools/hash_operator_password.py."""
    try:
        algorithm, iterations_text, salt_text, digest_text = encoded.split("$", 3)
        if algorithm != "pbkdf2_sha256":
            return False
        iterations = int(iterations_text)
        if iterations < 200_000:
            return False
        candidate = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), _b64decode(salt_text), iterations)
        return hmac.compare_digest(_b64encode(candidate), digest_text)
    except (TypeError, ValueError):
        return False


def issue_session(*, user_id: str, role: str, secret: bytes, ttl_seconds: int) -> str:
    now = int(time.time())
    payload = {"user_id": user_id, "role": role, "issued_at": now, "expires_at": now + ttl_seconds, "nonce": secrets.token_urlsafe(16)}
    encoded = _b64encode(json.dumps(payload, separators=(",", ":"), sort_keys=True).encode("utf-8"))
    signature = _b64encode(hmac.new(secret, encoded.encode("ascii"), hashlib.sha256).digest())
    return f"{encoded}.{signature}"


def read_session(token: str | None) -> dict[str, Any] | None:
    if not token:
        return None
    try:
        encoded, supplied_signature = token.rsplit(".", 1)
        _, _, secret, _ = _config()
        expected_signature = _b64encode(hmac.new(secret, encoded.encode("ascii"), hashlib.sha256).digest())
        if not hmac.compare_digest(supplied_signature, expected_signature):
            return None
        payload = json.loads(_b64decode(encoded))
        now = int(time.time())
        expires_at = int(payload.get("expires_at", 0))
        nonce = payload.get("nonce")
        if payload.get("role") != "OPERATOR" or expires_at <= now:
            return None
        if not isinstance(payload.get("user_id"), str) or not payload["user_id"]:
            return None
        if not isinstance(nonce, str) or not nonce:
            return None
        for item in [item for item, expiry in _revoked_session_nonces.items() if expiry <= now]:
            _revoked_session_nonces.pop(item, None)
        if nonce in _revoked_session_nonces:
            return None
        return payload
    except (HTTPException, TypeError, ValueError, json.JSONDecodeError):
        return None


def session_from_request(request: Request) -> dict[str, Any] | None:
    return read_session(request.cookies.get(COOKIE_NAME))


def require_operator_session(request: Request) -> dict[str, Any]:
    session = session_from_request(request)
    if not session:
        raise HTTPException(status_code=401, detail={"message": "Operator session is required", "reason_code": "AUTH_SESSION_REQUIRED"})
    return session


def _set_session_cookie(response: Response, token: str, ttl_seconds: int) -> None:
    response.set_cookie(
        key=COOKIE_NAME,
        value=token,
        max_age=ttl_seconds,
        httponly=True,
        secure=os.getenv("IDN_COOKIE_SECURE", "false").lower() == "true",
        samesite="lax",
        path="/",
    )


@router.post("/login")
def login(body: LoginRequest, response: Response) -> dict[str, Any]:
    username, password_hash, secret, ttl = _config()
    if not hmac.compare_digest(body.username, username) or not verify_password(body.password, password_hash):
        raise HTTPException(status_code=401, detail={"message": "Invalid username or password", "reason_code": "AUTH_INVALID_CREDENTIALS"})
    token = issue_session(user_id=username, role="OPERATOR", secret=secret, ttl_seconds=ttl)
    _set_session_cookie(response, token, ttl)
    return {"user_id": username, "display_name": username, "role": "OPERATOR", "expires_in_seconds": ttl}


@router.post("/logout")
def logout(request: Request, response: Response) -> dict[str, bool]:
    session = require_operator_session(request)
    _revoked_session_nonces[session["nonce"]] = int(session["expires_at"])
    response.delete_cookie(COOKIE_NAME, path="/", httponly=True, secure=os.getenv("IDN_COOKIE_SECURE", "false").lower() == "true", samesite="lax")
    return {"ok": True}


@router.get("/me")
def me(request: Request) -> dict[str, Any]:
    session = require_operator_session(request)
    return {"user_id": session["user_id"], "display_name": session["user_id"], "role": session["role"], "issued_at": session["issued_at"], "expires_at": session["expires_at"]}
